import { useState } from "react";
import { Home, Trophy, Loader2, Printer, Medal, Users } from "lucide-react";
import { useQuery } from "@tanstack/react-query";
import api from "@/lib/api";
import { toast } from "sonner";

// ─── Types ────────────────────────────────────────────────────────────────────

interface StudentRank {
    studentId: string;
    studentName: string;
    admNo: string;
    className: string;
    classId: string;
    subjects: { name: string; marks: number; outOf: number }[];
    totalMarks: number;
    totalOutOf: number;
    average: number;
    grade: string;
    rank: number;
}

// ─── Auto-grade helper ────────────────────────────────────────────────────────

function calcGrade(pct: number): string {
    if (pct >= 80) return "A";
    if (pct >= 70) return "B+";
    if (pct >= 60) return "B";
    if (pct >= 50) return "C+";
    if (pct >= 40) return "C";
    if (pct >= 33) return "D";
    return "F";
}

// ─── Print helper ─────────────────────────────────────────────────────────────

function printRankings(
    exam: any,
    rankings: StudentRank[],
    institute: any,
    classLabel: string
) {
    const win = window.open("", "_blank");
    if (!win) { toast.error("Allow popups to print"); return; }

    const schoolName = institute?.schoolName || institute?.name || "School";
    const rows = rankings.map((s, i) => `
        <tr style="background:${i < 3 ? ["#fffbeb","#f0fff4","#fdf4ff"][i] : i%2===0?"white":"#f8fafc"}">
            <td style="text-align:center;font-weight:900;font-size:14px;padding:10px 8px;color:${["#f59e0b","#10b981","#8b5cf6"][i]||"#64748b"}">${i < 3 ? ["🥇","🥈","🥉"][i] : i + 1}</td>
            <td style="font-weight:700;padding:10px 8px">${s.studentName}</td>
            <td style="padding:10px 8px;color:#64748b">${s.admNo || "—"}</td>
            <td style="padding:10px 8px;color:#64748b">${s.className || "—"}</td>
            <td style="text-align:center;padding:10px 8px">${s.subjects.length}</td>
            <td style="text-align:right;font-weight:900;padding:10px 8px">${s.totalMarks}/${s.totalOutOf}</td>
            <td style="text-align:right;padding:10px 8px">${s.average.toFixed(1)}%</td>
            <td style="text-align:center;font-weight:900;padding:10px 8px;color:#5C67F2">${s.grade}</td>
        </tr>
    `).join("");

    win.document.write(`<!DOCTYPE html><html><head><title>Rankings — ${exam?.name || "Exam"}</title>
    <style>
      body{font-family:Arial,sans-serif;padding:32px;max-width:900px;margin:0 auto;color:#1e293b}
      .header{text-align:center;border-bottom:3px solid #5C67F2;padding-bottom:14px;margin-bottom:20px}
      h1{color:#5C67F2;font-size:18px;font-weight:900;text-transform:uppercase;margin:0}
      h2{font-size:13px;color:#64748b;margin:4px 0 0}
      table{width:100%;border-collapse:collapse}
      th{background:#5C67F2;color:white;padding:9px 8px;font-size:9px;text-transform:uppercase;font-weight:700;text-align:left}
      .footer{text-align:center;margin-top:28px;font-size:9px;color:#94a3b8;border-top:1px dashed #e2e8f0;padding-top:10px}
    </style></head><body>
    <div class="header">
      <h1>${schoolName}</h1>
      <h2>${exam?.name || "Examination"} — ${classLabel} Rankings</h2>
      <p style="font-size:10px;color:#94a3b8">${exam?.term || ""} ${exam?.academicYear || ""}</p>
    </div>
    <table>
      <thead><tr>
        <th>Rank</th><th>Student Name</th><th>Adm No</th><th>Class</th>
        <th>Subjects</th><th style="text-align:right">Total Marks</th>
        <th style="text-align:right">Average %</th><th>Grade</th>
      </tr></thead>
      <tbody>${rows}</tbody>
    </table>
    <div class="footer">Generated by ShuleCloud ERP · ${new Date().toLocaleString()}</div>
    <script>window.onload=()=>window.print()</script>
    </body></html>`);
    win.document.close();
}

// ─── Component ────────────────────────────────────────────────────────────────

export default function ExamRankings() {
    const [selectedExam, setSelectedExam] = useState("");
    const [viewMode, setViewMode] = useState<"overall" | "by-class">("overall");
    const [selectedClass, setSelectedClass] = useState("ALL");

    // Fetch all exams
    const { data: exams = [] } = useQuery({
        queryKey: ["exams"],
        queryFn: async () => {
            const r = await api.get("/exams");
            return Array.isArray(r.data) ? r.data : [];
        },
    });

    // Fetch institute for print header
    const { data: institute } = useQuery({
        queryKey: ["tenant_profile"],
        queryFn: async () => {
            const r = await api.get("/tenant_profile");
            return Array.isArray(r.data) ? r.data[0] : r.data;
        },
    });

    // Fetch marks for selected exam
    const { data: rawMarks = [], isLoading } = useQuery({
        queryKey: ["exam_marks_for_ranking", selectedExam],
        queryFn: async () => {
            const r = await api.get(`/academics/exam-marks?examId=${selectedExam}`);
            return Array.isArray(r.data) ? r.data : [];
        },
        enabled: !!selectedExam,
    });

    // ── Aggregate marks into per-student rankings ────────────────────────────
    const studentMap: Record<string, StudentRank> = {};

    rawMarks.forEach((m: any) => {
        const sid = m.studentId;
        if (!sid) return;
        if (!studentMap[sid]) {
            studentMap[sid] = {
                studentId: sid,
                studentName: m.studentName || "Unknown",
                admNo: m.admNo || m.admissionNo || "",
                className: m.className || m.stream || "",
                classId: m.classId || "",
                subjects: [],
                totalMarks: 0,
                totalOutOf: 0,
                average: 0,
                grade: "—",
                rank: 0,
            };
        }

        const marks = Number(m.marksObtained || 0);
        const outOf = Number(m.totalMarks || 100);

        studentMap[sid].subjects.push({
            name: m.subjectName || "—",
            marks,
            outOf,
        });

        // Only count non-absent (marksObtained > 0 or explicitly present)
        if (m.attendanceStatus !== "Absent") {
            studentMap[sid].totalMarks += marks;
            studentMap[sid].totalOutOf += outOf;
        }
    });

    // Compute average + grade, then rank
    const allStudents: StudentRank[] = Object.values(studentMap).map(s => {
        const avg = s.totalOutOf > 0 ? (s.totalMarks / s.totalOutOf) * 100 : 0;
        return { ...s, average: avg, grade: calcGrade(avg) };
    }).sort((a, b) => b.totalMarks - a.totalMarks)
      .map((s, i) => ({ ...s, rank: i + 1 }));

    // ── Classes for filter tabs ───────────────────────────────────────────────
    const classes = ["ALL", ...Array.from(new Set(allStudents.map(s => s.className).filter(Boolean)))];

    // ── Per-class grouping ────────────────────────────────────────────────────
    const classBuckets: Record<string, StudentRank[]> = {};
    allStudents.forEach(s => {
        const key = s.className || "Unassigned";
        if (!classBuckets[key]) classBuckets[key] = [];
        classBuckets[key].push(s);
    });
    // Re-rank within each class
    Object.values(classBuckets).forEach(arr => {
        arr.sort((a, b) => b.totalMarks - a.totalMarks);
        arr.forEach((s, i) => { s.rank = i + 1; });
    });

    // ── Filtered list for overall view ───────────────────────────────────────
    const displayList = selectedClass === "ALL"
        ? allStudents
        : allStudents.filter(s => s.className === selectedClass);

    const exam = exams.find((e: any) => e._id === selectedExam);
    const classLabel = selectedClass === "ALL" ? "All Classes" : selectedClass;

    // ─────────────────────────────────────────────────────────────────────────
    return (
        <div className="flex-1 bg-[#F8FAFC] min-h-screen flex flex-col pb-20 font-sans">
            {/* Breadcrumb */}
            <div className="bg-white border-b border-gray-100 px-6 py-4 flex items-center justify-between shadow-sm sticky top-0 z-10">
                <div className="flex items-center gap-2 text-sm">
                    <Home className="w-4 h-4 text-[#5C67F2]" />
                    <span className="text-gray-300">/</span>
                    <span className="font-bold text-gray-600">Exams</span>
                    <span className="text-gray-300">/</span>
                    <span className="font-black text-[#5C67F2]">Student Rankings</span>
                </div>
                {displayList.length > 0 && (
                    <button onClick={() => printRankings(exam, displayList, institute, classLabel)}
                        className="h-9 px-4 bg-white border border-slate-200 hover:border-indigo-300 text-slate-600 hover:text-[#5C67F2] font-black text-xs uppercase tracking-widest rounded-xl flex items-center gap-2 transition-all">
                        <Printer className="w-4 h-4" /> Print {classLabel}
                    </button>
                )}
            </div>

            <div className="flex-1 max-w-7xl mx-auto w-full px-6 pt-8">
                <div className="mb-6">
                    <h1 className="text-3xl font-black text-slate-900 uppercase tracking-tight flex items-center gap-3">
                        <Trophy className="w-7 h-7 text-amber-500" /> Student Rankings
                    </h1>
                    <p className="text-slate-400 text-xs font-bold uppercase tracking-wider mt-1">Auto-ranked by total marks — per class and overall</p>
                </div>

                {/* Controls row */}
                <div className="flex flex-wrap gap-4 items-end mb-6">
                    {/* Exam selector */}
                    <div className="relative w-80">
                        <div className="absolute -top-3 left-4 bg-slate-800 text-white text-[8px] px-2 py-0.5 rounded-full font-black tracking-widest z-10 uppercase">Select Exam</div>
                        <select value={selectedExam} onChange={e => { setSelectedExam(e.target.value); setSelectedClass("ALL"); }}
                            className="w-full h-11 px-4 bg-white border border-slate-100 rounded-xl focus:outline-none focus:border-[#5C67F2] text-xs font-bold text-slate-700 shadow-sm">
                            <option value="">— Choose an Exam —</option>
                            {exams.map((e: any) => (
                                <option key={e._id} value={e._id}>
                                    {e.name || e.type} · {e.term} {e.academicYear}
                                </option>
                            ))}
                        </select>
                    </div>

                    {/* View mode */}
                    {allStudents.length > 0 && (
                        <div className="flex rounded-2xl overflow-hidden border border-slate-100 shadow-sm">
                            <button onClick={() => setViewMode("overall")}
                                className={`px-5 py-2.5 text-[10px] font-black uppercase tracking-wide transition-all flex items-center gap-2 ${viewMode === "overall" ? "bg-[#5C67F2] text-white" : "bg-white text-slate-500 hover:bg-slate-50"}`}>
                                <Trophy className="w-3.5 h-3.5" /> Overall
                            </button>
                            <button onClick={() => setViewMode("by-class")}
                                className={`px-5 py-2.5 text-[10px] font-black uppercase tracking-wide transition-all flex items-center gap-2 ${viewMode === "by-class" ? "bg-[#5C67F2] text-white" : "bg-white text-slate-500 hover:bg-slate-50"}`}>
                                <Users className="w-3.5 h-3.5" /> By Class
                            </button>
                        </div>
                    )}

                    {/* Class filter (overall mode only) */}
                    {viewMode === "overall" && classes.length > 2 && (
                        <div className="flex gap-2 flex-wrap">
                            {classes.map(cls => (
                                <button key={cls} onClick={() => setSelectedClass(cls)}
                                    className={`px-4 py-2 rounded-xl text-[10px] font-black uppercase tracking-wide border transition-all ${selectedClass === cls ? "bg-[#5C67F2] text-white border-[#5C67F2]" : "bg-white text-slate-500 border-slate-100 hover:border-slate-200"}`}>
                                    {cls === "ALL" ? `All (${allStudents.length})` : `${cls} (${allStudents.filter(s => s.className === cls).length})`}
                                </button>
                            ))}
                        </div>
                    )}
                </div>

                {/* ── Summary cards (if exam selected) ── */}
                {allStudents.length > 0 && (
                    <div className="grid grid-cols-2 md:grid-cols-4 gap-4 mb-6">
                        {[
                            { label: "Students Ranked", value: allStudents.length, color: "text-[#5C67F2]" },
                            { label: "Classes", value: Object.keys(classBuckets).length, color: "text-amber-600" },
                            { label: "Class Average", value: `${(allStudents.reduce((s, r) => s + r.average, 0) / allStudents.length).toFixed(1)}%`, color: "text-emerald-600" },
                            { label: "Top Score", value: `${allStudents[0]?.totalMarks || 0}/${allStudents[0]?.totalOutOf || 0}`, color: "text-rose-600" },
                        ].map(s => (
                            <div key={s.label} className="bg-white p-4 rounded-[1.5rem] border border-slate-100 shadow-sm text-center">
                                <p className="text-[9px] font-black uppercase tracking-widest text-slate-400">{s.label}</p>
                                <p className={`text-xl font-black mt-1 ${s.color}`}>{s.value}</p>
                            </div>
                        ))}
                    </div>
                )}

                {/* ── TOP 3 Podium (overall view) ── */}
                {viewMode === "overall" && displayList.length >= 3 && (
                    <div className="grid grid-cols-3 gap-4 mb-6">
                        {[
                            { pos: 0, emoji: "🥇", bg: "bg-amber-50", border: "border-amber-200", color: "text-amber-600" },
                            { pos: 1, emoji: "🥈", bg: "bg-slate-50", border: "border-slate-200", color: "text-slate-500" },
                            { pos: 2, emoji: "🥉", bg: "bg-orange-50", border: "border-orange-200", color: "text-orange-600" },
                        ].map(({ pos, emoji, bg, border, color }) => {
                            const s = displayList[pos];
                            if (!s) return null;
                            return (
                                <div key={pos} className={`${bg} border-2 ${border} rounded-[2rem] p-5 text-center`}>
                                    <div className="text-4xl mb-2">{emoji}</div>
                                    <p className="font-black text-slate-800 text-sm">{s.studentName}</p>
                                    <p className="text-[9px] text-slate-500 font-bold uppercase mt-0.5">{s.className || s.admNo}</p>
                                    <p className={`text-xl font-black mt-2 ${color}`}>{s.totalMarks}/{s.totalOutOf}</p>
                                    <p className="text-[9px] text-slate-400 font-bold uppercase">{s.average.toFixed(1)}% · {s.grade}</p>
                                </div>
                            );
                        })}
                    </div>
                )}

                {/* ── OVERALL Table ─────────────────────────────────────────── */}
                {viewMode === "overall" && (
                    <RankingTable
                        students={displayList}
                        isLoading={isLoading && !!selectedExam}
                        hasExam={!!selectedExam}
                        showClassColumn
                    />
                )}

                {/* ── BY CLASS View ─────────────────────────────────────────── */}
                {viewMode === "by-class" && (
                    <>
                        {!selectedExam ? (
                            <EmptyState />
                        ) : isLoading ? (
                            <div className="flex items-center justify-center h-40 gap-2 text-slate-400 text-xs font-bold uppercase">
                                <Loader2 className="w-5 h-5 animate-spin text-[#5C67F2]" />Computing rankings...
                            </div>
                        ) : Object.keys(classBuckets).length === 0 ? (
                            <div className="flex flex-col items-center justify-center h-40 gap-2 text-slate-300 text-xs font-bold uppercase">
                                <Medal className="w-8 h-8" />No marks found for this exam
                            </div>
                        ) : (
                            <div className="space-y-8">
                                {Object.entries(classBuckets)
                                    .sort(([a], [b]) => a.localeCompare(b))
                                    .map(([cls, students]) => (
                                        <div key={cls}>
                                            <div className="flex items-center justify-between mb-3">
                                                <div className="flex items-center gap-3">
                                                    <div className="w-8 h-8 rounded-xl bg-indigo-50 flex items-center justify-center">
                                                        <Users className="w-4 h-4 text-[#5C67F2]" />
                                                    </div>
                                                    <div>
                                                        <h3 className="font-black text-slate-800 text-sm uppercase tracking-wide">{cls}</h3>
                                                        <p className="text-[9px] text-slate-400 font-bold uppercase">{students.length} students ranked</p>
                                                    </div>
                                                </div>
                                                <button onClick={() => printRankings(exam, students, institute, cls)}
                                                    className="h-8 px-4 bg-white border border-slate-200 hover:border-indigo-300 text-slate-500 hover:text-[#5C67F2] font-black text-[9px] uppercase tracking-widest rounded-xl flex items-center gap-1.5 transition-all">
                                                    <Printer className="w-3.5 h-3.5" /> Print {cls}
                                                </button>
                                            </div>
                                            <RankingTable students={students} showClassColumn={false} />
                                        </div>
                                    ))}
                            </div>
                        )}
                    </>
                )}
            </div>
        </div>
    );
}

// ─── Sub-components ───────────────────────────────────────────────────────────

function EmptyState() {
    return (
        <div className="flex flex-col items-center justify-center h-40 gap-2 text-slate-300 text-xs font-bold uppercase">
            <Trophy className="w-8 h-8" />Select an exam to view rankings
        </div>
    );
}

function RankingTable({ students, isLoading = false, hasExam = true, showClassColumn = true }: {
    students: StudentRank[]; isLoading?: boolean; hasExam?: boolean; showClassColumn?: boolean;
}) {
    if (!hasExam) return <EmptyState />;

    if (isLoading) return (
        <div className="flex items-center justify-center h-40 gap-2 text-slate-400 text-xs font-bold uppercase">
            <Loader2 className="w-5 h-5 animate-spin text-[#5C67F2]" />Computing rankings...
        </div>
    );

    if (students.length === 0) return (
        <div className="flex flex-col items-center justify-center h-40 gap-2 text-slate-300 text-xs font-bold uppercase bg-white rounded-[2.5rem] border border-slate-100 shadow-sm">
            <Medal className="w-8 h-8" />No marks found for this exam
        </div>
    );

    return (
        <div className="bg-white rounded-[2.5rem] border border-slate-100 shadow-sm overflow-hidden p-6">
            <div className="overflow-x-auto">
                <table className="w-full text-left border-collapse text-xs">
                    <thead>
                        <tr className="bg-slate-50 border-b border-slate-100 text-[10px] font-black uppercase text-slate-400 tracking-wider">
                            <th className="py-4 px-4 w-14">Rank</th>
                            <th className="py-4 px-4">Student Name</th>
                            <th className="py-4 px-4">Adm No</th>
                            {showClassColumn && <th className="py-4 px-4">Class</th>}
                            <th className="py-4 px-4 text-center">Subjects</th>
                            <th className="py-4 px-4 text-right">Total Marks</th>
                            <th className="py-4 px-4 text-right">Average %</th>
                            <th className="py-4 px-4 text-center">Grade</th>
                            <th className="py-4 px-4">Performance</th>
                        </tr>
                    </thead>
                    <tbody className="divide-y divide-slate-100">
                        {students.map((s, i) => {
                            const isTop = i < 3;
                            const avg = s.average;
                            return (
                                <tr key={s.studentId} className={`transition-colors ${isTop ? "bg-amber-50/20" : "hover:bg-slate-50/50"}`}>
                                    <td className="py-3 px-4 text-center">
                                        <span className={`text-lg font-black ${i === 0 ? "text-amber-500" : i === 1 ? "text-slate-400" : i === 2 ? "text-orange-500" : "text-slate-400 text-sm"}`}>
                                            {i < 3 ? ["🥇","🥈","🥉"][i] : i + 1}
                                        </span>
                                    </td>
                                    <td className="py-3 px-4 font-black text-slate-800">{s.studentName}</td>
                                    <td className="py-3 px-4 font-bold text-slate-500">{s.admNo || "—"}</td>
                                    {showClassColumn && <td className="py-3 px-4 font-bold text-slate-600">{s.className || "—"}</td>}
                                    <td className="py-3 px-4 text-center font-bold text-slate-500">{s.subjects.length}</td>
                                    <td className="py-3 px-4 text-right font-black text-slate-800">{s.totalMarks}/{s.totalOutOf}</td>
                                    <td className="py-3 px-4 text-right font-black text-[#5C67F2]">{avg.toFixed(1)}%</td>
                                    <td className="py-3 px-4 text-center">
                                        <span className={`px-2.5 py-1 rounded-xl text-[9px] font-black uppercase ${avg >= 70 ? "bg-emerald-50 text-emerald-600" : avg >= 50 ? "bg-amber-50 text-amber-600" : "bg-rose-50 text-rose-500"}`}>
                                            {s.grade}
                                        </span>
                                    </td>
                                    <td className="py-3 px-4">
                                        <div className="flex items-center gap-2">
                                            <div className="h-2 bg-slate-100 rounded-full overflow-hidden w-20 flex-shrink-0">
                                                <div className={`h-full rounded-full ${avg >= 70 ? "bg-emerald-400" : avg >= 50 ? "bg-amber-400" : "bg-rose-400"}`}
                                                    style={{ width: `${Math.min(avg, 100)}%` }} />
                                            </div>
                                            {i === 0 && <span className="text-[9px] text-amber-500 font-black uppercase">Top</span>}
                                        </div>
                                    </td>
                                </tr>
                            );
                        })}
                    </tbody>
                    {students.length > 3 && (
                        <tfoot>
                            <tr className="bg-slate-50 border-t border-slate-100 text-[10px] font-black text-slate-500">
                                <td colSpan={showClassColumn ? 5 : 4} className="py-3 px-4 uppercase">Class Average</td>
                                <td className="py-3 px-4 text-right">{Math.round(students.reduce((s, r) => s + r.totalMarks, 0) / students.length)}</td>
                                <td className="py-3 px-4 text-right text-[#5C67F2]">{(students.reduce((s, r) => s + r.average, 0) / students.length).toFixed(1)}%</td>
                                <td colSpan={2}></td>
                            </tr>
                        </tfoot>
                    )}
                </table>
            </div>
        </div>
    );
}
