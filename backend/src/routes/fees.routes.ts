// ── M-PESA Till/Paybill transactions ──────────────────────────────────────────
// All C2B payments received on THIS school's Till/Paybill (Safaricom confirmation
// callbacks are stored in the meta DB as mpesa_c2b_payments). Filterable by the
// M-PESA code (TransID), payer phone (MSISDN) or payer name.
router.get('/fees/till-transactions', async (req: Request, res: Response) => {
    try {
        const tenantDb = getRequestDb(req);
        const cfg = await resolveMpesaConfig(tenantDb).catch(() => null as any);
        const codes = [cfg?.shortcode, cfg?.tillNumber].map((v: any) => String(v || '').trim()).filter(Boolean);
        const { code, phone, name, from, to } = req.query as any;
        const fromD = from ? new Date(from) : null;
        const toD = to ? (() => { const d = new Date(to); d.setHours(23, 59, 59); return d; })() : null;

        type Row = { code: string; phone: string; name: string; account: string; amount: number; shortcode: string; paidAt: any; source: string };
        const all: Row[] = [];

        // 1) Raw C2B confirmations (meta DB) for this school's shortcode/till.
        if (codes.length) {
            const c2b = await getMetaDb().collection('mpesa_c2b_payments').find({ BusinessShortCode: { $in: codes } }).sort({ receivedAt: -1 }).limit(3000).toArray().catch(() => []);
            c2b.forEach((r: any) => all.push({
                code: r.TransID || '', phone: r.MSISDN || '',
                name: [r.FirstName, r.MiddleName, r.LastName].filter(Boolean).join(' ').trim() || '—',
                account: r.BillRefNumber || '', amount: Number(r.TransAmount) || 0,
                shortcode: r.BusinessShortCode || '', paidAt: r.receivedAt || (r.TransTime ? parseMpesaTime(r.TransTime) : null), source: 'C2B',
            }));
        }

        // 2) The tenant's applied payments (STK push, C2B and wallet flow through here).
        //    This is where most real data lives, so the page works even without C2B URLs.
        const pays = await tenantDb.collection('payments').find({ is_voided: { $ne: true } }).sort({ createdAt: -1 }).limit(5000).toArray().catch(() => []);
        pays.forEach((p: any) => {
            const m = String(p.method || p.payment_mode || '').toUpperCase();
            if (!/MPESA|M-PESA|MOBILE|PAYBILL|TILL|WALLET/.test(m)) return;   // M-PESA / wallet only
            all.push({
                code: p.mpesaCode || p.transactionId || p.reference || p.receipt_no || '',
                phone: p.phone || '', name: p.studentName || p.payerName || '—',
                account: p.registrationNo || p.account || '', amount: Number(p.amount) || 0,
                shortcode: codes[0] || '', paidAt: p.payment_date || p.createdAt || null, source: m.includes('WALLET') ? 'Wallet' : 'M-PESA',
            });
        });

        // Dedupe by M-PESA code (a C2B row and its applied payment can both appear).
        const seen = new Set<string>();
        let data = all.filter(r => { const k = (r.code || '').toUpperCase(); if (k && seen.has(k)) return false; if (k) seen.add(k); return true; });

        // Apply filters in-memory (sources have different field names).
        if (code) { const c = String(code).toLowerCase(); data = data.filter(r => r.code.toLowerCase().includes(c)); }
        if (phone) { const ph = String(phone).replace(/\D/g, ''); data = data.filter(r => String(r.phone).replace(/\D/g, '').includes(ph)); }
        if (name) { const n = String(name).toLowerCase(); data = data.filter(r => r.name.toLowerCase().includes(n)); }
        if (fromD) data = data.filter(r => r.paidAt && new Date(r.paidAt) >= fromD);
        if (toD) data = data.filter(r => r.paidAt && new Date(r.paidAt) <= toD);

        data.sort((a, b) => new Date(b.paidAt || 0).getTime() - new Date(a.paidAt || 0).getTime());
        const total = data.reduce((s, d) => s + d.amount, 0);
        res.json({ data, summary: { count: data.length, total }, configured: codes.length > 0, shortcodes: codes });
    } catch (e: any) { res.status(500).json({ message: e.message }); }
});

// ── Apply a Till payment by its M-PESA code ───────────────────────────────────
// For Till (Buy Goods) numbers, Safaricom does not push C2B confirmations, so a
// clerk records the payment from the customer's M-PESA SMS: paste the code +
// amount and choose the student. We verify against Daraja Transaction Status when
// reconciliation credentials are configured (async, best-effort), and always
// record + allocate the payment via the same path C2B uses.
router.post('/fees/till-transactions/apply', async (req: Request, res: Response) => {
    try {
        const db = getRequestDb(req);
        const { code, amount, phone, studentId, registrationNo, invoiceId } = req.body || {};
        const mpesaCode = String(code || '').trim().toUpperCase();
        const amt = Number(amount) || 0;
        if (!mpesaCode) return res.status(400).json({ message: 'M-PESA transaction code is required.' });
        if (!/^[A-Z0-9]{8,15}$/.test(mpesaCode)) return res.status(400).json({ message: 'That does not look like a valid M-PESA code (e.g. SLJ7ABC123).' });
        if (amt <= 0) return res.status(400).json({ message: 'Enter the amount paid.' });
        if (!studentId && !registrationNo) return res.status(400).json({ message: 'Select the student this payment belongs to.' });

        // Guard against applying the same code twice.
        const dup = await db.collection('payments').findOne({ is_voided: { $ne: true }, $or: [{ mpesaCode }, { transactionId: mpesaCode }, { reference: mpesaCode }] });
        if (dup) return res.status(409).json({ message: `Code ${mpesaCode} has already been recorded (receipt ${dup.receipt_no || dup._id}).` });

        // Resolve the student's name for nicer records.
        let studentName: string | undefined; let regNo = registrationNo;
        try {
            const q: any = studentId ? { _id: new ObjectId(String(studentId)) } : { $or: [{ registrationNo }, { admNo: registrationNo }] };
            const stu = await db.collection('students').findOne(q);
            if (stu) { studentName = stu.studentName; regNo = regNo || stu.registrationNo || stu.admNo; }
        } catch { /* ignore */ }

        // Best-effort Daraja verification (async — Safaricom posts the result to our
        // ResultURL). Only attempted when reconciliation credentials exist.
        let verification: 'queued' | 'unavailable' = 'unavailable';
        try {
            const cfg = await resolveMpesaConfig(db);
            if (cfg.initiator && cfg.securityCredential && platformCallbackBase()) {
                const base = platformCallbackBase().replace(/mpesa/gi, 'pesa');
                await transactionStatus(cfg, { transactionId: mpesaCode, resultUrl: `${base}/pesa/transaction-status/result`, queueUrl: `${base}/pesa/timeout`, remarks: 'Till payment verification' });
                verification = 'queued';
            }
        } catch { /* verification optional — never blocks the manual record */ }

        await applyMpesaPayment(db, { studentId: studentId ? String(studentId) : undefined, studentName, registrationNo: regNo, invoiceId, amount: amt, receipt: mpesaCode, phone });
        res.json({ ok: true, message: `Payment ${mpesaCode} recorded${studentName ? ' for ' + studentName : ''} and applied to outstanding fees.`, verification });
    } catch (e: any) { res.status(500).json({ message: e.message }); }
});

// ── Verify a Till payment code with Safaricom (async) ─────────────────────────
// Fires a Daraja Transaction Status query. Safaricom posts the verdict to our
// result callback (stored in mpesa_code_verifications). The UI then polls
// /fees/till-transactions/verify-status. Requires Initiator + SecurityCredential.
router.post('/fees/till-transactions/verify', async (req: Request, res: Response) => {
    try {
        const db = getRequestDb(req);
        const mpesaCode = String(req.body?.code || '').trim().toUpperCase();
        if (!/^[A-Z0-9]{8,15}$/.test(mpesaCode)) return res.status(400).json({ message: 'Enter a valid M-PESA code first.' });

        // Already known (recorded earlier, or a prior verification)?
        const already = await db.collection('payments').findOne({ is_voided: { $ne: true }, $or: [{ mpesaCode }, { transactionId: mpesaCode }] });
        if (already) return res.json({ status: 'recorded', amount: already.amount, message: `Already recorded (receipt ${already.receipt_no}).` });

        const cfg = await resolveMpesaConfig(db);
        if (!cfg.initiator || !cfg.securityCredential) {
            return res.json({ status: 'unavailable', message: 'Automatic verification needs an API Initiator + Security Credential (Settings → M-PESA → Reconciliation). You can still record the payment manually from the SMS.' });
        }
        if (!platformCallbackBase()) return res.json({ status: 'unavailable', message: 'Platform callback URL is not configured by the operator.' });

        const base = platformCallbackBase().replace(/mpesa/gi, 'pesa');
        // Clear any stale verdict for this code, then query.
        await getMetaDb().collection('mpesa_code_verifications').deleteOne({ code: mpesaCode }).catch(() => { });
        await transactionStatus(cfg, { transactionId: mpesaCode, resultUrl: `${base}/pesa/transaction-status/result`, queueUrl: `${base}/pesa/timeout`, remarks: 'Till code verification' });
        res.json({ status: 'checking', message: 'Checking with Safaricom… this can take a few seconds.' });
    } catch (e: any) { res.status(400).json({ status: 'error', message: e.message }); }
});

