router.post('/schools/:sid/payments', requireRole('ADMIN'), requireManualPayments, async (req: Request, res: Response) => {
    try {
    const db = getRequestDb(req);
        const schoolId = getSchoolId(req);
        const user = (req as any).user;
        const { invoice_id, amount, method, reference, payment_date, remarks } = req.body;

        if (!invoice_id || amount === undefined || !method || !payment_date) {
            return res.status(400).json({
                data: null,
                meta: {},
                errors: [{ code: 'VALIDATION_ERROR', message: 'Missing invoice_id, amount, method, or payment_date' }]
            });
        }

        const invoice = await db.collection('invoices').findOne({ _id: new ObjectId(invoice_id), $or: [{ schoolId }, { schoolId: { $exists: false } }] });
        if (!invoice) {
            return res.status(404).json({
                data: null,
                meta: {},
                errors: [{ code: 'NOT_FOUND', message: 'Invoice not found' }]
            });
        }

        const payAmount = parseFloat(amount);
        if (payAmount <= 0) {
            return res.status(400).json({
                data: null,
                meta: {},
                errors: [{ code: 'VALIDATION_ERROR', message: 'Payment amount must be greater than zero' }]
            });
        }

        // Overpayment is now ALLOWED — the invoice is cleared and the excess is
        // banked as a carry-forward credit (auto-applied to the next invoice).
        const invBalance = Number(invoice.balance ?? (invoice.total_due - invoice.amount_paid)) || 0;
        const excess = Math.max(0, payAmount - invBalance);

        const receipt_no = await getNextReceiptNo(db, schoolId);

        const payment = {
            _id: new ObjectId(),
            receipt_no,
            schoolId,
            invoice_id,
            student_id: invoice.student_id,
            amount: payAmount,
            method,
            reference: reference || null,
            payment_date,
            remarks: remarks || null,
            collected_by: user.sub,
            is_voided: false,
            createdAt: new Date().toISOString()
        };

        await db.collection('payments').insertOne(payment);

        // Mirror the money-in into Accounting so every payment is detected there.
        const stu = await db.collection('students').findOne({ _id: new ObjectId(String(invoice.student_id)) }).catch(() => null);
        await postFeePaymentJournal(db, payment, stu?.studentName || stu?.name);

        // Update Invoice: cap at fully paid; the excess goes to credit, not balance.
        const applied = payAmount - excess;                  // amount that hit this invoice
        const amount_paid = Number(invoice.amount_paid || 0) + applied;
        const balance = Math.max(0, Number(invoice.total_due) - amount_paid);
        const status = balance <= 0 ? 'PAID' : 'PARTIAL';

        await db.collection('invoices').updateOne(
            { _id: invoice._id },
            { $set: { amount_paid, balance, status, updatedAt: new Date().toISOString() } }
        );

        // Bank the overpayment as a carry-forward credit on the student.
        if (excess > 0) {
            const { addCredit } = await import('../services/feeCredit.service');
            await addCredit(db, { studentId: String(invoice.student_id), studentName: stu?.studentName || stu?.name, amount: excess, reason: 'Overpayment', receipt: receipt_no });
        }

        res.status(201).json({
            data: {
                id: payment._id,
                receipt_no,
                amount: payAmount,
                invoice_status: status,
                invoice_balance: balance,
                receipt_pdf_url: `/api/v1/schools/${schoolId}/payments/${payment._id}/receipt`
            },
            meta: {},
            errors: []
        });
    } catch (e: any) {
        res.status(500).json({ data: null, meta: {}, errors: [{ code: 'SERVER_ERROR', message: e.message }] });
    }
});

