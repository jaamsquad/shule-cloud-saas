const getUserFromToken = (req: Request) => {
    const authHeader = req.headers.authorization;
    if (!authHeader || !authHeader.startsWith('Bearer ')) return null;
    const token = authHeader.split(' ')[1];
    try {
        const decoded: any = jwt.verify(token, process.env.JWT_SECRET || 'secret');
        return decoded;
    } catch {
        return null;
    }
};

const getUserRole = async (userId: string) => {
    const db = getMetaDb();
    try {
        const userRole = await db.collection('UserRole').findOne({ userId: new ObjectId(userId) });
        if (!userRole) return 'STUDENT';
        const roleDoc = await db.collection('Role').findOne({ _id: userRole.roleId });
        if (!roleDoc) return 'STUDENT';
        const name = (roleDoc.name || '').toUpperCase();
        if (name.includes('SUPER') || name.includes('OWNER')) return 'SUPERADMIN';
        if (name.includes('ADMIN') || name.includes('BURSAR')) return 'ADMIN';
        if (name.includes('TEACHER')) return 'TEACHER';
        return 'STUDENT';
    } catch {
        return 'STUDENT';
    }
};

const requireRole = (minRole: 'STUDENT' | 'TEACHER' | 'ADMIN' | 'SUPERADMIN') => {
    const rolesOrder = ['STUDENT', 'TEACHER', 'ADMIN', 'SUPERADMIN'];
    return async (req: Request, res: Response, next: any) => {
        const user = getUserFromToken(req);
        if (!user) {
            return res.status(401).json({
                data: null,
                meta: {},
                errors: [{ code: 'UNAUTHORIZED', message: 'Missing or invalid authentication token' }]
            });
        }
        (req as any).user = user;
        const role = await getUserRole(user.sub);
        (req as any).userRole = role;

        if (rolesOrder.indexOf(role) < rolesOrder.indexOf(minRole)) {
            return res.status(403).json({
                data: null,
                meta: {},
                errors: [{ code: 'FORBIDDEN', message: 'Insufficient role privileges' }]
            });
        }
        next();
    };
};

